"""Shared helpers for the offline `parse` tests: the fake GROBID service and ways to run `parse` through the CLI.

The `grobid` and `wechsel` fixtures that use them are in conftest.py. No PDF is committed: the "PDFs" are a
few generated bytes, and the fake service maps their sha256 to a committed TEI fixture (see fixtures/tei/README.md).
"""

import hashlib
import json
from email.parser import BytesParser
from email.policy import HTTP
from pathlib import Path

import httpx

from chatbot_rag_tokenizers.cli import main

ROOT = Path(__file__).parents[1]
REPO_CONFIG = ROOT / "config" / "parse.toml"
TEI = Path(__file__).parent / "fixtures" / "tei"
GROBID_URL = "http://localhost:8070/api/processFulltextDocument"
WECHSEL_TITLE = "WECHSEL: Effective initialization of subword embeddings for cross-lingual transfer of monolingual language models"


def fake_pdf(name: str) -> bytes:
    return f"%PDF-1.5\n% {name}\n%%EOF\n".encode()


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


# How a request fails when the service isn't there: nothing listens on the port (refused), the container
# stopped while the request was being read (reset), or it closed the connection without an answer.
DROPS: dict[str, tuple[type[httpx.TransportError], str]] = {
    "refused": (httpx.ConnectError, "[Errno 61] Connection refused"),
    "reset": (httpx.ReadError, "[Errno 54] Connection reset by peer"),
    "disconnected": (httpx.RemoteProtocolError, "Server disconnected without sending a response."),
}


class FakeGrobid:
    """Stands in for the GROBID service: the sha256 of the uploaded PDF picks the TEI it answers with.

    Every request's URL and form fields are recorded. It can also fail on chosen files the ways the real
    service does (an error answer, a timeout), or go away: then each request fails the way a stopped
    service fails one, its connection refused, reset or dropped (DROPS).
    """

    def __init__(self) -> None:
        self.tei_by_hash: dict[str, str] = {}
        self.requests: list[tuple[str, list[tuple[str, str]]]] = []
        self.errors: dict[str, tuple[int, str]] = {}
        self.timeouts: set[str] = set()
        self.down: str | None = None  # a key of DROPS: the service has gone away, and requests fail this way
        self.down_after: int | None = None  # with down: answer this many requests first, then go away

    def serve(self, pdf: bytes, tei_fixture: str) -> None:
        self.tei_by_hash[sha256(pdf)] = (TEI / tei_fixture).read_text()

    def fail(self, pdf: bytes, status: int, body: str) -> None:
        self.errors[sha256(pdf)] = (status, body)

    def time_out(self, pdf: bytes) -> None:
        self.timeouts.add(sha256(pdf))

    def handle(self, request: httpx.Request) -> httpx.Response:
        request.read()
        head = f"Content-Type: {request.headers['content-type']}\r\n\r\n".encode()
        form = BytesParser(policy=HTTP).parsebytes(head + request.content)
        fields: list[tuple[str, str]] = []
        upload = b""
        for part in form.iter_parts():
            name = str(part.get_param("name", header="content-disposition"))
            payload = part.get_payload(decode=True)
            assert isinstance(payload, bytes)
            if name == "input":
                upload = payload
            else:
                fields.append((name, payload.decode()))
        self.requests.append((str(request.url), fields))
        uploaded = sha256(upload)
        if self.down and (self.down_after is None or len(self.requests) > self.down_after):
            error, message = DROPS[self.down]
            raise error(message, request=request)
        if uploaded in self.timeouts:
            raise httpx.ReadTimeout("timed out", request=request)
        if uploaded in self.errors:
            status, body = self.errors[uploaded]
            return httpx.Response(status, text=body, request=request)
        if str(request.url) != GROBID_URL or uploaded not in self.tei_by_hash:
            return httpx.Response(500, text="unexpected request", request=request)
        return httpx.Response(200, text=self.tei_by_hash[uploaded], request=request)


def seed_pdf(tmp_path: Path, grobid: FakeGrobid, name: str, tei_fixture: str) -> Path:
    """A PDF under ``tmp_path/pdfs`` with this name, which the fake service answers with this TEI fixture."""
    pdf = tmp_path / "pdfs" / name
    pdf.parent.mkdir(exist_ok=True)
    pdf.write_bytes(fake_pdf(name))
    grobid.serve(pdf.read_bytes(), tei_fixture)
    return pdf


def run_parse(tmp_path: Path, *files: Path, config: Path = REPO_CONFIG, options: tuple[str, ...] = ()) -> None:
    main(
        [
            "parse",
            "--config", str(config),
            "--cache", str(tmp_path / "cache"),
            "--report", str(tmp_path / "parse-report.md"),
            *options,
            "--files", *map(str, files),
        ]
    )  # fmt: skip


def config_with_budget(tmp_path: Path, token_budget: int) -> Path:
    """The repo's parse config with another token budget, written beside the test's other files."""
    text = REPO_CONFIG.read_text().replace("token_budget = 350", f"token_budget = {token_budget}")
    text = text.replace('tokenizer_file = "', f'tokenizer_file = "{REPO_CONFIG.parent}/')
    path = tmp_path / f"parse-{token_budget}.toml"
    path.write_text(text)
    return path


def read_chunks(tmp_path: Path, pdf: Path) -> list[dict]:
    """The Chunks the parse cache holds for one file."""
    [path] = (tmp_path / "cache" / sha256(pdf.read_bytes())).glob("*.chunks.jsonl")
    return [json.loads(line) for line in path.read_text().splitlines()]
