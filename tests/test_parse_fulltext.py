"""Offline runs of `parse` with no `--files`: it parses what `fetch` recorded in the Snapshot's full-text record
for the included Editions of the manifest.

The record is a fixture written by the test, in the shape `fetch` writes; the PDFs are generated bytes
that the fake GROBID service maps to committed TEI fixtures.
"""

import csv
import json
from pathlib import Path

import pytest

from chatbot_rag_tokenizers.cli import main
from chatbot_rag_tokenizers.collection.manifest import COLUMNS
from parse_support import REPO_CONFIG, FakeGrobid, fake_pdf, sha256


def record_line(edition_id: str, file: str, pdf: bytes | None) -> dict:
    """One line of `data/snapshot/fulltext/pdfs.jsonl`; no bytes means the Edition has no open PDF."""
    if pdf is None:
        return {
            "edition_id": edition_id, "file": "", "url": "https://example.org/a.pdf", "sha256": "", "size": 0,
            "fetched_at": "2026-10-16", "unavailable": "https://example.org/a.pdf: HTTP 403",
        }  # fmt: skip
    return {
        "edition_id": edition_id, "file": file, "url": f"https://example.org/{file}", "sha256": sha256(pdf),
        "size": len(pdf), "fetched_at": "2026-10-16", "unavailable": "",
    }  # fmt: skip


class Corpus:
    """A Snapshot with a full-text record, a PDFs directory and a manifest, as `fetch` leaves them.

    Every Edition with a recorded file is included, unless ``excluded`` says otherwise.
    """

    def __init__(self, root: Path, grobid: FakeGrobid) -> None:
        self.root = root
        self.snapshot = root / "snapshot"
        self.pdfs = root / "pdfs"
        self.pdfs.mkdir()
        self.manifest = root / "manifest.csv"
        self.grobid = grobid
        self.lines: list[dict] = []
        self.excluded_editions: set[str] = set()

    def excluded(self, edition_id: str) -> None:
        """Give the Edition an excluded Relevance verdict in the manifest, as a withdrawn preprint gets."""
        self.excluded_editions.add(edition_id)

    def fetched(self, edition_id: str, file: str, label: str, on_disk: bytes | None = None) -> bytes:
        """Record a fetched file; ``on_disk`` puts other bytes in the PDFs directory than the record pins."""
        pdf = fake_pdf(label)
        self.lines.append(record_line(edition_id, file, pdf))
        (self.pdfs / file).write_bytes(pdf if on_disk is None else on_disk)
        self.grobid.serve(pdf, "wechsel_2112.06598v2.tei.xml")
        return pdf

    def no_open_pdf(self, edition_id: str) -> None:
        self.lines.append(record_line(edition_id, "", None))

    def save(self) -> None:
        path = self.snapshot / "fulltext" / "pdfs.jsonl"
        path.parent.mkdir(parents=True)
        path.write_text("".join(json.dumps(line, sort_keys=True) + "\n" for line in self.lines))
        files: dict[str, list[str]] = {}
        for line in self.lines:
            names = files.setdefault(line["edition_id"], [])
            if line["file"]:
                names.append(f"{line['file']} {line['sha256']}")
        with self.manifest.open("w", newline="") as f:
            writer = csv.DictWriter(f, fieldnames=COLUMNS, restval="", lineterminator="\n")
            writer.writeheader()
            for edition_id, names in sorted(files.items()):
                verdict = "excluded" if edition_id in self.excluded_editions else "included"
                writer.writerow({"edition_id": edition_id, "relevance_verdict": verdict, "pdf_files": "|".join(names)})

    def parse(self, save: bool = True) -> None:
        if save:
            self.save()
        main(
            [
                "parse",
                "--config", str(REPO_CONFIG),
                "--cache", str(self.root / "cache"),
                "--report", str(self.root / "parse-report.md"),
                "--snapshot", str(self.snapshot),
                "--pdfs", str(self.pdfs),
                "--manifest", str(self.manifest),
            ]
        )  # fmt: skip

    def anchors(self, pdf: bytes) -> set[tuple[str, str, str]]:
        """The (pinned id, Version, sha256) the cached Chunks of a file cite."""
        return {anchor[1:] for anchor in self.editions_and_anchors(pdf)}

    def editions_and_anchors(self, pdf: bytes) -> set[tuple[str, str, str, str]]:
        """The (Edition id, pinned id, Version, sha256) the cached Chunks of a file carry."""
        [path] = (self.root / "cache" / sha256(pdf)).glob("*.chunks.jsonl")
        chunks = [json.loads(line) for line in path.read_text().splitlines()]
        assert chunks
        return {(c["edition_id"], c["pinned_id"], c["version"], c["file_sha256"]) for c in chunks}


@pytest.fixture
def corpus(tmp_path: Path, grobid: FakeGrobid) -> Corpus:
    return Corpus(tmp_path, grobid)


def test_every_recorded_file_is_parsed_and_cited_by_the_pinned_id_the_record_gives(corpus):
    v1 = corpus.fetched("2112.06598v2", "2112.06598v1.pdf", "wechsel v1")
    v2 = corpus.fetched("2112.06598v2", "2112.06598v2.pdf", "wechsel v2")
    old_style = corpus.fetched("hep-th/9901001v2", "hep-th_9901001v1.pdf", "old-style v1")
    venue = corpus.fetched("10.5555/lrm.2022.7", "10.5555_lrm.2022.7.pdf", "venue")

    corpus.parse()

    # Each Chunk carries the Edition the record pins as well as the Version its file holds.
    assert corpus.editions_and_anchors(v1) == {("2112.06598v2", "2112.06598v1", "v1", sha256(v1))}
    assert corpus.editions_and_anchors(v2) == {("2112.06598v2", "2112.06598v2", "v2", sha256(v2))}
    assert corpus.editions_and_anchors(old_style) == {("hep-th/9901001v2", "hep-th/9901001v1", "v1", sha256(old_style))}
    assert corpus.editions_and_anchors(venue) == {("10.5555/lrm.2022.7", "10.5555/lrm.2022.7", "", sha256(venue))}


def test_an_edition_recorded_as_having_no_open_pdf_is_skipped(corpus, grobid):
    corpus.no_open_pdf("2020.acl-main.1")
    pdf = corpus.fetched("2112.06598v2", "2112.06598v2.pdf", "wechsel v2")

    corpus.parse()

    assert len(grobid.requests) == 1
    assert corpus.anchors(pdf) == {("2112.06598v2", "v2", sha256(pdf))}
    report = (corpus.root / "parse-report.md").read_text()
    assert "- Files: 1" in report
    assert "2020.acl-main.1" not in report


def test_only_the_files_of_included_editions_are_parsed(corpus, grobid):
    withdrawn = corpus.fetched("2506.00291v2", "2506.00291v1.pdf", "withdrawn v1")
    corpus.excluded("2506.00291v2")
    included = corpus.fetched("2112.06598v2", "2112.06598v2.pdf", "wechsel v2")

    corpus.parse()

    assert len(grobid.requests) == 1
    assert corpus.anchors(included) == {("2112.06598v2", "v2", sha256(included))}
    assert not (corpus.root / "cache" / sha256(withdrawn)).exists()
    assert "2506.00291" not in (corpus.root / "parse-report.md").read_text()


def test_a_file_the_edition_is_no_longer_pinned_to_is_not_parsed(corpus, grobid):
    # A refreshed Snapshot re-pinned the Edition from v2 to v3. The record keeps v1 and v2 under the old Edition id;
    # the manifest row, now 2112.06598v3, lists v1 and v3 only.
    v1 = corpus.fetched("2112.06598v2", "2112.06598v1.pdf", "wechsel v1")
    old_latest = corpus.fetched("2112.06598v2", "2112.06598v2.pdf", "wechsel v2")
    current = corpus.fetched("2112.06598v3", "2112.06598v3.pdf", "wechsel v3")
    corpus.save()
    corpus.manifest.write_text(
        corpus.manifest.read_text()
        .replace(f"2112.06598v2,,,,,,,,,,,,,,,,,,,,,,included,,,,,2112.06598v1.pdf {sha256(v1)}|2112.06598v2.pdf {sha256(old_latest)},,\n", "")
        .replace("2112.06598v3.pdf", f"2112.06598v1.pdf {sha256(v1)}|2112.06598v3.pdf")
    )

    corpus.parse(save=False)

    assert len(grobid.requests) == 2
    assert not (corpus.root / "cache" / sha256(old_latest)).exists()
    # Chunks cite the Edition the manifest pins now, not the one the record line was written under.
    assert corpus.editions_and_anchors(v1) == {("2112.06598v3", "2112.06598v1", "v1", sha256(v1))}
    assert corpus.editions_and_anchors(current) == {("2112.06598v3", "2112.06598v3", "v3", sha256(current))}


def test_a_missing_or_changed_file_is_reported_with_a_fetch_hint_and_not_parsed(corpus, grobid, capsys):
    missing = corpus.fetched("2112.06598v2", "2112.06598v1.pdf", "wechsel v1")
    (corpus.pdfs / "2112.06598v1.pdf").unlink()
    changed = corpus.fetched("2112.06598v2", "2112.06598v2.pdf", "wechsel v2", on_disk=fake_pdf("re-downloaded"))
    fine = corpus.fetched("P16-1162", "P16-1162.pdf", "venue")

    with pytest.raises(SystemExit) as exit:
        corpus.parse()

    message = str(exit.value.code)
    assert "2 recorded file(s) weren't parsed" in message
    assert "`just fetch`" in message
    assert f"2112.06598v1.pdf is missing; the record pins sha256 {sha256(missing)}" in message
    assert f"has sha256 {sha256(fake_pdf('re-downloaded'))}, but the record pins {sha256(changed)}" in message
    assert len(grobid.requests) == 1
    assert corpus.anchors(fine) == {("P16-1162", "", sha256(fine))}
    assert not (corpus.root / "cache" / sha256(changed)).exists()
    assert not (corpus.root / "cache" / sha256(fake_pdf("re-downloaded"))).exists()


def test_parse_leaves_the_manifest_unchanged(corpus):
    corpus.fetched("2112.06598v2", "2112.06598v2.pdf", "wechsel v2")
    corpus.save()
    before = corpus.manifest.read_bytes()

    corpus.parse(save=False)

    assert corpus.manifest.read_bytes() == before
